package codegen

import (
	"fmt"
	"strings"
)

// GenerateMocks creates a File containing mock implementations for the given interfaces.
func GenerateMocks(ifaces []*InterfaceInfo, outPath string) (*File, error) {
	if len(ifaces) == 0 {
		return nil, fmt.Errorf("no interfaces provided for mock generation")
	}

	pkgName := ifaces[0].PkgName
	file := NewFile(outPath, pkgName)
	file.SetHeader("// Code generated by mockgen. DO NOT EDIT.\n")
	file.Import("sync")

	for _, iface := range ifaces {
		file.AddImports(iface.Imports)

		mockName := iface.MockName()

		// Compile-time interface assertion
		file.P("// Compile-time interface assertion.")
		file.P("var _ ", iface.Name, " = (*", mockName, ")(nil)")
		file.P()

		// Struct declaration
		file.P("// ", mockName, " is a mock implementation of ", iface.Name, ".")
		file.P("type ", mockName, " struct {")

		// Function fields
		for _, m := range iface.Methods {
			file.P("\t// ", m.Name, "Func mocks the ", m.Name, " method.")
			file.P("\t", m.Name, "Func func(", m.ParamsSignature(), ") ", m.ResultsSignature())
			file.P()
		}

		// Calls tracking struct
		file.P("\t// calls tracks calls to the methods.")
		file.P("\tcalls struct {")
		for _, m := range iface.Methods {
			if len(m.Params) == 0 {
				file.P("\t\t", m.Name, " []struct{}")
			} else {
				file.P("\t\t", m.Name, " []struct {")
				for _, p := range m.Params {
					pType := strings.Replace(p.Type, "...", "[]", 1)
					file.P("\t\t\t", p.ExportedName(), " ", pType)
				}
				file.P("\t\t}")
			}
		}
		file.P("\t}")

		// Mutex locks for call recording thread-safety
		for _, m := range iface.Methods {
			file.P("\tlock", m.Name, " sync.RWMutex")
		}
		file.P("}")
		file.P()

		// Method implementations
		for _, m := range iface.Methods {
			file.P("// ", m.Name, " calls ", m.Name, "Func.")
			file.P("func (mock *", mockName, ") ", m.Name, "(", m.ParamsSignature(), ") ", m.ResultsSignature(), " {")
			file.P("\tif mock.", m.Name, "Func == nil {")
			file.P("\t\tpanic(\"", mockName, ".", m.Name, "Func: method is nil but ", iface.Name, ".", m.Name, " was just called\")")
			file.P("\t}")
			file.P("\tmock.lock", m.Name, ".Lock()")

			if len(m.Params) == 0 {
				file.P("\tmock.calls.", m.Name, " = append(mock.calls.", m.Name, ", struct{}{})")
			} else {
				file.P("\tmock.calls.", m.Name, " = append(mock.calls.", m.Name, ", struct {")
				for _, p := range m.Params {
					pType := strings.Replace(p.Type, "...", "[]", 1)
					file.P("\t\t", p.ExportedName(), " ", pType)
				}
				file.P("\t}{")
				for _, p := range m.Params {
					file.P("\t\t", p.ExportedName(), ": ", p.Name, ",")
				}
				file.P("\t})")
			}

			file.P("\tmock.lock", m.Name, ".Unlock()")

			if len(m.Results) == 0 {
				file.P("\tmock.", m.Name, "Func(", m.CallArgs(), ")")
			} else {
				file.P("\treturn mock.", m.Name, "Func(", m.CallArgs(), ")")
			}
			file.P("}")
			file.P()

			// Calls accessor method
			file.P("// ", m.Name, "Calls returns all calls made to ", m.Name, ".")
			if len(m.Params) == 0 {
				file.P("func (mock *", mockName, ") ", m.Name, "Calls() []struct{} {")
			} else {
				file.P("func (mock *", mockName, ") ", m.Name, "Calls() []struct {")
				for _, p := range m.Params {
					pType := strings.Replace(p.Type, "...", "[]", 1)
					file.P("\t", p.ExportedName(), " ", pType)
				}
				file.P("} {")
			}
			file.P("\tmock.lock", m.Name, ".RLock()")
			file.P("\tdefer mock.lock", m.Name, ".RUnlock()")
			file.P("\treturn mock.calls.", m.Name)
			file.P("}")
			file.P()
		}
	}

	return file, nil
}
