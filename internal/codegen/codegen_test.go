func TestFile_GenerationAndImports(t *testing.T) {
	f := codegen.NewFile("test.go", "testpkg")
	f.SetHeader("// Code generated by test. DO NOT EDIT.\n")

	f.Import("context")
	f.Import("fmt")
	f.Import("github.com/masterkeysrd/saturn/internal/platform/agent", "agent")
	f.Import("github.com/masterkeysrd/saturn/internal/platform/errors", "customerr")

	f.P("// Compile-time interface assertion.")
	f.P("var _ = ", f.QualifiedIdent("context", "Background"))
	f.P("type Sample struct {")
	f.P("\tName string")
	f.P("}")

	content, err := f.Content()
	require.NoError(t, err)

	contentStr := string(content)
	assert.Contains(t, contentStr, "package testpkg")
	assert.Contains(t, contentStr, `"context"`)
	assert.Contains(t, contentStr, `"fmt"`)
	assert.Contains(t, contentStr, `customerr "github.com/masterkeysrd/saturn/internal/platform/errors"`)
	assert.Contains(t, contentStr, `"github.com/masterkeysrd/saturn/internal/platform/agent"`)
	assert.Contains(t, contentStr, "type Sample struct {")

	// Verify standard library imports appear before third-party imports
	stdIdx := strings.Index(contentStr, `"context"`)
	thirdPartyIdx := strings.Index(contentStr, `"github.com/masterkeysrd/saturn/internal/platform/agent"`)
	assert.True(t, stdIdx < thirdPartyIdx, "standard library imports should precede third-party imports")
}

func TestFile_Save(t *testing.T) {
	tempDir := t.TempDir()
	filePath := filepath.Join(tempDir, "subpkg", "generated.go")

	f := codegen.NewFile(filePath, "subpkg")
	f.Import("context")
	f.P("func Run(ctx context.Context) {}")

	err := f.Save()
	require.NoError(t, err)

	readData, err := os.ReadFile(filePath)
	require.NoError(t, err)

	expected, err := f.Content()
	require.NoError(t, err)
	assert.Equal(t, expected, readData)
}

