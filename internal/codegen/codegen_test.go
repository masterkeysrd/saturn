func TestZeroValueOf(t *testing.T) {
	tests := []struct {
		typeStr  string
		expected string
	}{
		{"*User", "nil"},
		{"[]string", "nil"},
		{"map[string]any", "nil"},
		{"chan int", "nil"},
		{"<-chan string", "nil"},
		{"func()", "nil"},
		{"any", "nil"},
		{"interface{}", "nil"},
		{"string", `""`},
		{"bool", "false"},
		{"int", "0"},
		{"int64", "0"},
		{"uint", "0"},
		{"uint64", "0"},
		{"byte", "0"},
		{"rune", "0"},
		{"float32", "0"},
		{"float64", "0"},
		{"error", "nil"},
		{"User", "User{}"},
		{"agent.Agent", "agent.Agent{}"},
	}

	for _, tc := range tests {
		t.Run(tc.typeStr, func(t *testing.T) {
			assert.Equal(t, tc.expected, codegen.ZeroValueOf(tc.typeStr))
		})
	}
}

func TestMethodInfo_Helpers(t *testing.T) {
	method := codegen.MethodInfo{
		Name: "UpdateAgent",
		Doc:  "// UpdateAgent updates the agent.\n// @transactional",
		Params: []codegen.Param{
			{Name: "ctx", Type: "context.Context"},
			{Name: "id", Type: "string"},
			{Name: "tags", Type: "...string", IsVariadic: true},
		},
		Results: []codegen.Result{
			{Name: "agent", Type: "*agent.Agent", ZeroValue: "nil"},
			{Name: "err", Type: "error", ZeroValue: "nil"},
		},
	}

	assert.True(t, method.HasAnnotation("@transactional"))
	assert.True(t, method.HasAnnotation("TRANSACTIONAL"))
	assert.False(t, method.HasAnnotation("@mock"))
	assert.True(t, method.HasContextParam())
	assert.True(t, method.HasErrorResult())

	assert.Equal(t, "ctx context.Context, id string, tags ...string", method.ParamsSignature())
	assert.Equal(t, "ctx, id, tags...", method.CallArgs())
	assert.Equal(t, "(*agent.Agent, error)", method.ResultsSignature())
	assert.Equal(t, []string{"nil"}, method.ZeroReturns())

	assert.Equal(t, "Ctx", method.Params[0].ExportedName())
	assert.Equal(t, "Id", method.Params[1].ExportedName())
}

func TestMethodInfo_SingleResultAndNoResult(t *testing.T) {
	m1 := codegen.MethodInfo{
		Name: "Delete",
		Results: []codegen.Result{
			{Type: "error", ZeroValue: "nil"},
		},
	}
	assert.Equal(t, "error", m1.ResultsSignature())
	assert.Empty(t, m1.ZeroReturns())

	m2 := codegen.MethodInfo{
		Name: "Close",
	}
	assert.Equal(t, "", m2.ResultsSignature())
	assert.False(t, m2.HasContextParam())
	assert.False(t, m2.HasErrorResult())
}

