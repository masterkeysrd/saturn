func TestParser_ParseDir_And_ParseTarget(t *testing.T) {
	tempDir := t.TempDir()
	sourceCode := `package sample

import (
	"context"
	agentv1 "apis/saturn/platform/agent/v1"
)

// Greeter provides greetings.
// @Mock
type Greeter interface {
	// Greet generates a greeting.
	Greet(ctx context.Context, name string, opts ...string) (*agentv1.Agent, error)
	// Ping sends a ping.
	Ping(context.Context) error
}

// TransactionalWorker performs tasks atomically.
// @transactional
type TransactionalWorker interface {
	Work(ctx context.Context) error
}

type PlainWorker interface {
	Do()
}
`
	err := os.WriteFile(filepath.Join(tempDir, "sample.go"), []byte(sourceCode), 0644)
	require.NoError(t, err)

	// Test ParseDir
	ifaces, err := codegen.ParseDir(tempDir)
	require.NoError(t, err)
	require.Len(t, ifaces, 3)

	// Test ParseTarget
	greeter, err := codegen.ParseTarget(tempDir, "Greeter")
	require.NoError(t, err)
	assert.Equal(t, "Greeter", greeter.Name)
	assert.Equal(t, "sample", greeter.PkgName)
	assert.True(t, greeter.HasAnnotation("@Mock"))
	assert.Equal(t, "apis/saturn/platform/agent/v1", greeter.Imports["agentv1"])
	require.Len(t, greeter.Methods, 2)

	greetMethod := greeter.Methods[0]
	assert.Equal(t, "Greet", greetMethod.Name)
	require.Len(t, greetMethod.Params, 3)
	assert.Equal(t, "ctx", greetMethod.Params[0].Name)
	assert.Equal(t, "name", greetMethod.Params[1].Name)
	assert.Equal(t, "opts", greetMethod.Params[2].Name)
	assert.True(t, greetMethod.Params[2].IsVariadic)
	require.Len(t, greetMethod.Results, 2)
	assert.Equal(t, "*agentv1.Agent", greetMethod.Results[0].Type)
	assert.Equal(t, "error", greetMethod.Results[1].Type)

	pingMethod := greeter.Methods[1]
	assert.Equal(t, "Ping", pingMethod.Name)
	require.Len(t, pingMethod.Params, 1)
	assert.Equal(t, "ctx", pingMethod.Params[0].Name) // Automatically named ctx for context.Context

	// Test FindInterfacesWithAnnotation
	mockIfaces, err := codegen.FindInterfacesWithAnnotation(tempDir, "@Mock")
	require.NoError(t, err)
	require.Len(t, mockIfaces, 1)
	assert.Equal(t, "Greeter", mockIfaces[0].Name)

	txIfaces, err := codegen.FindInterfacesWithAnnotation(tempDir, "@transactional")
	require.NoError(t, err)
	require.Len(t, txIfaces, 1)
	assert.Equal(t, "TransactionalWorker", txIfaces[0].Name)

	// Test ParseTarget not found
	_, err = codegen.ParseTarget(tempDir, "NonExistent")
	require.Error(t, err)
	assert.Contains(t, err.Error(), "not found")
}

func TestGenerateMocks(t *testing.T) {
	ifaces := []*codegen.InterfaceInfo{
		{
			PkgName: "testpkg",
			Name:    "Notifier",
			Methods: []codegen.MethodInfo{
				{
					Name: "Notify",
					Params: []codegen.Param{
						{Name: "ctx", Type: "context.Context"},
						{Name: "msg", Type: "string"},
					},
					Results: []codegen.Result{
						{Type: "error", ZeroValue: "nil"},
					},
				},
				{
					Name: "Ping",
				},
				{
					Name: "Broadcast",
					Params: []codegen.Param{
						{Name: "recipients", Type: "...string", IsVariadic: true},
					},
					Results: []codegen.Result{
						{Type: "int", ZeroValue: "0"},
						{Type: "error", ZeroValue: "nil"},
					},
				},
			},
		},
	}

	file, err := codegen.GenerateMocks(ifaces, "mocks_test.go")
	require.NoError(t, err)

	content, err := file.Content()
	require.NoError(t, err)

	str := string(content)
	assert.Contains(t, str, "package testpkg")
	assert.Contains(t, str, "var _ Notifier = (*NotifierMock)(nil)")
	assert.Contains(t, str, "type NotifierMock struct")
	assert.Contains(t, str, "NotifyFunc func(ctx context.Context, msg string) error")
	assert.Contains(t, str, "PingFunc func()")
	assert.Contains(t, str, "BroadcastFunc func(recipients ...string) (int, error)")
	assert.Contains(t, str, "NotifyCalls() []struct")
	assert.Contains(t, str, "PingCalls() []struct{}")
	assert.Contains(t, str, `panic("NotifierMock.NotifyFunc: method is nil but Notifier.Notify was just called")`)

	// Empty list should error
	_, err = codegen.GenerateMocks(nil, "mocks_test.go")
	require.Error(t, err)
}
