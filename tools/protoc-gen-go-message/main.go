package main

import (
	"context"
	"encoding/json"
	"fmt"
	"path/filepath"
	"time"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/reflect/protoregistry"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/dynamicpb"
	"google.golang.org/protobuf/types/pluginpb"
)

var (
	_ = context.Background
	_ = json.Marshal
	_ = time.Now
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		var types protoregistry.Types
		for _, f := range gen.Files {
			registerExtensions(&types, f.Desc)
		}

		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			generateFile(gen, f, &types)
		}
		return nil
	})
}

func registerExtensions(types *protoregistry.Types, desc protoreflect.Descriptor) {
	if fd, ok := desc.(protoreflect.FileDescriptor); ok {
		exts := fd.Extensions()
		for i := 0; i < exts.Len(); i++ {
			_ = types.RegisterExtension(dynamicpb.NewExtensionType(exts.Get(i)))
		}
		msgs := fd.Messages()
		for i := 0; i < msgs.Len(); i++ {
			registerExtensions(types, msgs.Get(i))
		}
	} else if md, ok := desc.(protoreflect.MessageDescriptor); ok {
		exts := md.Extensions()
		for i := 0; i < exts.Len(); i++ {
			_ = types.RegisterExtension(dynamicpb.NewExtensionType(exts.Get(i)))
		}
		msgs := md.Messages()
		for i := 0; i < msgs.Len(); i++ {
			registerExtensions(types, msgs.Get(i))
		}
	}
}

type topicMessage struct {
	GoIdent protogen.GoIdent
	Topic   string
}

func generateFile(gen *protogen.Plugin, f *protogen.File, types *protoregistry.Types) {
	var messages []topicMessage

	for _, msg := range f.Messages {
		topic := getTopic(msg, types)
		if topic != "" {
			messages = append(messages, topicMessage{
				GoIdent: msg.GoIdent,
				Topic:   topic,
			})
		}
	}

	if len(messages) == 0 {
		return
	}

	filename := f.GeneratedFilenamePrefix + ".pb.message.go"
	g := gen.NewGeneratedFile(filename, f.GoImportPath)

	g.P("// Code generated by protoc-gen-go-message. DO NOT EDIT.")
	g.P("// Source: ", filepath.Base(f.Desc.Path()))
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()

	g.P("import (")
	g.P(`	"context"`)
	g.P()
	g.P(`	"google.golang.org/protobuf/proto"`)
	g.P(`	"github.com/masterkeysrd/saturn/internal/platform/eventbus"`)
	g.P(")")
	g.P()

	for _, msg := range messages {
		typeName := msg.GoIdent.GoName

		// Topic Constant
		g.P("// Topic", typeName, " is the eventbus topic for ", typeName, ".")
		g.P("const Topic", typeName, " = ", fmt.Sprintf("%q", msg.Topic))
		g.P()

		// Handler signature
		g.P("// ", typeName, "Handler is the strongly-typed callback for the '", msg.Topic, "' topic.")
		g.P("type ", typeName, "Handler func(ctx context.Context, payload *", typeName, ") error")
		g.P()

		// Subscribe helper
		g.P("// Subscribe", typeName, " binds a handler callback to the eventbus for '", msg.Topic, "'.")
		g.P("func Subscribe", typeName, "(engine *eventbus.Engine, subscriberID string, handler ", typeName, "Handler) {")
		g.P("	engine.Subscribe(", fmt.Sprintf("%q", msg.Topic), ", subscriberID, func(ctx context.Context, msg eventbus.Message) error {")
		g.P("		var payload ", typeName)
		g.P("		if err := proto.Unmarshal(msg.Payload, &payload); err != nil {")
		g.P("			return err")
		g.P("		}")
		g.P("		return handler(ctx, &payload)")
		g.P("	})")
		g.P("}")
		g.P()

		// Publish helper
		g.P("// Publish", typeName, " serializes and broadcasts the ", typeName, " message to the eventbus.")
		g.P("func Publish", typeName, "(ctx context.Context, engine *eventbus.Engine, msg *", typeName, ") error {")
		g.P("	payloadBytes, err := proto.Marshal(msg)")
		g.P("	if err != nil {")
		g.P("		return err")
		g.P("	}")
		g.P("	return engine.Publish(ctx, ", fmt.Sprintf("%q", msg.Topic), ", payloadBytes)")
		g.P("}")
		g.P()
	}
}

func getTopic(msg *protogen.Message, types *protoregistry.Types) string {
	optionsProto := msg.Desc.Options().(*descriptorpb.MessageOptions)
	raw, err := proto.Marshal(optionsProto)
	if err != nil {
		return ""
	}

	var resolvedOptions descriptorpb.MessageOptions
	err = proto.UnmarshalOptions{Resolver: types}.Unmarshal(raw, &resolvedOptions)
	if err != nil {
		return ""
	}

	var topic string
	resolvedOptions.ProtoReflect().Range(func(fd protoreflect.FieldDescriptor, v protoreflect.Value) bool {
		// Field number 50002 corresponds to our topic option
		if fd.Number() == 50002 {
			topic = v.String()
			return false
		}
		return true
	})
	return topic
}
