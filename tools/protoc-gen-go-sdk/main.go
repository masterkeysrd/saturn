package main

import (
	"fmt"
	"regexp"
	"strings"

	"google.golang.org/genproto/googleapis/api/annotations"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/pluginpb"
)

func main() {
	protogen.Options{}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, f := range gen.Files {
			if !f.Generate || len(f.Services) == 0 {
				continue
			}
			generateSDKFile(gen, f)
		}
		return nil
	})
}

func generateSDKFile(gen *protogen.Plugin, f *protogen.File) {
	filename := f.GeneratedFilenamePrefix + "_sdk.pb.go"
	g := gen.NewGeneratedFile(filename, f.GoImportPath)

	g.P("// Code generated by protoc-gen-go-sdk. DO NOT EDIT.")
	g.P("package ", f.GoPackageName)
	g.P()
	g.P("import (")
	g.P(`	"context"`)
	g.P(`	"fmt"`)
	g.P(`	"strings"`)
	g.P()
	g.P(`	"github.com/masterkeysrd/saturn/apis/saturn"`)
	g.P(")")
	g.P()
	g.P("var (")
	g.P("	_ = fmt.Sprintf")
	g.P("	_ = strings.TrimSpace")
	g.P(")")
	g.P()

	for _, service := range f.Services {
		clientName := "Client"

		g.P("// ", clientName, " provides typed HTTP SDK operations for the ", service.GoName, " service.")
		g.P("type ", clientName, " struct {")
		g.P("	base *saturn.Client")
		g.P("}")
		g.P()
		g.P("// NewClient creates a new ", service.GoName, " HTTP SDK client.")
		g.P("func NewClient(cfg saturn.Config) *Client {")
		g.P("	return &Client{base: saturn.NewClient(cfg)}")
		g.P("}")
		g.P()

		for _, method := range service.Methods {
			generateSDKMethod(g, method)
		}
	}
}

var pathParamRegex = regexp.MustCompile(`\{([a-zA-Z0-9_]+)\}`)

func generateSDKMethod(g *protogen.GeneratedFile, method *protogen.Method) {
	httpMethod := "POST"
	pathPattern := ""
	bodyField := "*"

	opts := method.Desc.Options()
	if proto.HasExtension(opts, annotations.E_Http) {
		ext := proto.GetExtension(opts, annotations.E_Http)
		if rule, ok := ext.(*annotations.HttpRule); ok {
			bodyField = rule.GetBody()
			switch pattern := rule.GetPattern().(type) {
			case *annotations.HttpRule_Get:
				httpMethod = "GET"
				pathPattern = pattern.Get
			case *annotations.HttpRule_Post:
				httpMethod = "POST"
				pathPattern = pattern.Post
			case *annotations.HttpRule_Put:
				httpMethod = "PUT"
				pathPattern = pattern.Put
			case *annotations.HttpRule_Delete:
				httpMethod = "DELETE"
				pathPattern = pattern.Delete
			case *annotations.HttpRule_Patch:
				httpMethod = "PATCH"
				pathPattern = pattern.Patch
			}
		}
	}

	if pathPattern == "" {
		pathPattern = fmt.Sprintf("/v1/%s", strings.ToLower(method.GoName))
	}

	if !strings.HasPrefix(pathPattern, "/api") {
		pathPattern = "/api" + pathPattern
	}

	inputType := g.QualifiedGoIdent(method.Input.GoIdent)
	outputType := g.QualifiedGoIdent(method.Output.GoIdent)

	g.P("// ", method.GoName, " executes ", httpMethod, " ", pathPattern, ".")
	g.P("func (c *Client) ", method.GoName, "(ctx context.Context, req *", inputType, ") (*", outputType, ", error) {")
	g.P("	var resp ", outputType)

	// Extract path variables from request
	pathVars := pathParamRegex.FindAllStringSubmatch(pathPattern, -1)
	if len(pathVars) > 0 {
		var fmtArgs []string
		fmtPathPattern := pathPattern
		for _, varMatch := range pathVars {
			rawVar := varMatch[0]
			varName := varMatch[1]
			getterName := "Get" + snakeToCamel(varName)
			fmtPathPattern = strings.Replace(fmtPathPattern, rawVar, "%s", 1)
			fmtArgs = append(fmtArgs, fmt.Sprintf("req.%s()", getterName))
		}
		g.P("	path := fmt.Sprintf(", quote(fmtPathPattern), ", ", strings.Join(fmtArgs, ", "), ")")
	} else {
		g.P("	path := ", quote(pathPattern))
	}

	var hasVersion, hasUpdateMask bool
	for _, field := range method.Input.Fields {
		if field.GoName == "Version" {
			hasVersion = true
		}
		if field.GoName == "UpdateMask" {
			hasUpdateMask = true
		}
	}

	// Query parameters handling
	g.P("	var query []string")
	if hasVersion {
		g.P("	if req.Version != nil {")
		g.P("		query = append(query, fmt.Sprintf(\"version=%d\", req.GetVersion()))")
		g.P("	}")
	}
	if hasUpdateMask {
		g.P("	if req.UpdateMask != nil {")
		g.P("		for _, p := range req.GetUpdateMask().GetPaths() {")
		g.P("			query = append(query, fmt.Sprintf(\"update_mask.paths=%s\", p))")
		g.P("		}")
		g.P("	}")
	}

	if httpMethod == "GET" || httpMethod == "DELETE" {
		if method.GoName == "ListBudgets" {
			g.P("	if req.View != nil {")
			g.P("		query = append(query, \"view=\" + req.GetView().String())")
			g.P("	}")
			g.P("	for _, st := range req.GetStatuses() {")
			g.P("		query = append(query, \"statuses=\" + st.String())")
			g.P("	}")
		} else if method.GoName == "ListInboxItems" {
			g.P("	if req.Status != nil {")
			g.P("		query = append(query, fmt.Sprintf(\"status=%s\", req.GetStatus().String()))")
			g.P("	}")
			g.P("	if req.DocType != nil {")
			g.P("		query = append(query, fmt.Sprintf(\"doc_type=%s\", req.GetDocType().String()))")
			g.P("	}")
		}
		g.P("	if len(query) > 0 {")
		g.P("		path += \"?\" + strings.Join(query, \"&\")")
		g.P("	}")
		g.P("	if err := c.base.Do(ctx, ", quote(httpMethod), ", path, nil, &resp); err != nil {")
	} else if bodyField != "" && bodyField != "*" {
		getterName := "Get" + snakeToCamel(bodyField)
		g.P("	if len(query) > 0 {")
		g.P("		path += \"?\" + strings.Join(query, \"&\")")
		g.P("	}")
		g.P("	payload := req.", getterName, "()")
		g.P("	if payload == nil {")
		g.P("		return nil, fmt.Errorf(", quote(bodyField+" payload is required"), ")")
		g.P("	}")
		g.P("	if err := c.base.Do(ctx, ", quote(httpMethod), ", path, payload, &resp); err != nil {")
	} else {
		g.P("	if len(query) > 0 {")
		g.P("		path += \"?\" + strings.Join(query, \"&\")")
		g.P("	}")
		g.P("	if err := c.base.Do(ctx, ", quote(httpMethod), ", path, req, &resp); err != nil {")
	}

	g.P("		return nil, err")
	g.P("	}")
	g.P("	return &resp, nil")
	g.P("}")
	g.P()
}

func snakeToCamel(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func quote(s string) string {
	return fmt.Sprintf("%q", s)
}
