package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/masterkeysrd/saturn/internal/codegen"
)

func main() {
	target := flag.String("target", "", "Name of the interface to decorate (required)")
	dir := flag.String("dir", ".", "Directory to parse")
	output := flag.String("output", "", "Output file path (defaults to <target>_tx.go in dir)")
	pkgFlag := flag.String("pkg", "", "Target package name (defaults to parsed package name)")
	flag.Parse()

	if *target == "" {
		fmt.Fprintln(os.Stderr, "Error: -target flag is required")
		flag.Usage()
		os.Exit(1)
	}

	info, err := codegen.ParseTarget(*dir, *target)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error parsing target %q in %q: %v\n", *target, *dir, err)
		os.Exit(1)
	}

	if *pkgFlag != "" {
		info.PkgName = *pkgFlag
	}

	outPath := *output
	if outPath == "" {
		outPath = filepath.Join(*dir, strings.ToLower(*target)+"_tx.go")
	}

	file, err := generateDecorator(info, outPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error generating decorator: %v\n", err)
		os.Exit(1)
	}

	if err := file.Save(); err != nil {
		fmt.Fprintf(os.Stderr, "Error writing output file %q: %v\n", outPath, err)
		os.Exit(1)
	}

	fmt.Printf("Successfully generated %s for interface %s (in package %s)\n", outPath, *target, info.PkgName)
}

func isTransactional(m codegen.MethodInfo) bool {
	return m.HasAnnotation("@transactional") ||
		m.HasAnnotation("@tx") ||
		m.HasAnnotation("tx:wrap")
}

func generateDecorator(info *codegen.InterfaceInfo, outPath string) (*codegen.File, error) {
	decoratorName := "Transactional" + info.Name

	file := codegen.NewFile(outPath, info.PkgName)
	file.SetHeader("// Code generated by txgen. DO NOT EDIT.\n")
	file.Import("context")
	file.Import("github.com/masterkeysrd/saturn/internal/platform/db")
	file.AddImports(info.Imports)

	// Validate transactional annotations
	for _, m := range info.Methods {
		if isTransactional(m) {
			if !m.HasContextParam() {
				return nil, fmt.Errorf("method %s is marked @transactional but does not accept context.Context as first argument", m.Name)
			}
			if !m.HasErrorResult() {
				return nil, fmt.Errorf("method %s is marked @transactional but does not return error as last return value", m.Name)
			}
		}
	}

	// Struct definition
	file.P("// ", decoratorName, " wraps a ", info.Name, " and manages database transactions")
	file.P("// for methods annotated with @transactional.")
	file.P("type ", decoratorName, " struct {")
	file.P("\tnext ", info.Name)
	file.P("\ttxr  db.Transactor")
	file.P("}")
	file.P()

	// Constructor
	file.P("// New", decoratorName, " creates a new ", decoratorName, " decorator.")
	file.P("func New", decoratorName, "(next ", info.Name, ", txr db.Transactor) *", decoratorName, " {")
	file.P("\treturn &", decoratorName, "{")
	file.P("\t\tnext: next,")
	file.P("\t\ttxr:  txr,")
	file.P("\t}")
	file.P("}")
	file.P()

	// Interface compile assertion
	file.P("// Compile-time interface assertion.")
	file.P("var _ ", info.Name, " = (*", decoratorName, ")(nil)")
	file.P()

	// Methods
	for _, m := range info.Methods {
		paramsSig := m.ParamsSignature()
		callArgs := m.CallArgs()
		retSig := m.ResultsSignature()
		retSigWithSpace := retSig
		if retSigWithSpace != "" {
			retSigWithSpace = " " + retSigWithSpace
		}

		if !isTransactional(m) {
			// Non-transactional: direct pass-through
			if len(m.Results) == 0 {
				file.P("func (t *", decoratorName, ") ", m.Name, "(", paramsSig, ") {")
				file.P("\tt.next.", m.Name, "(", callArgs, ")")
				file.P("}")
				file.P()
			} else {
				file.P("func (t *", decoratorName, ") ", m.Name, "(", paramsSig, ")", retSigWithSpace, " {")
				file.P("\treturn t.next.", m.Name, "(", callArgs, ")")
				file.P("}")
				file.P()
			}
			continue
		}

		// Transactional method
		ctxArgName := m.Params[0].Name
		zeroReturns := m.ZeroReturns()

		file.P("// ", m.Name, " executes next.", m.Name, " inside a database transaction.")
		file.P("func (t *", decoratorName, ") ", m.Name, "(", paramsSig, ")", retSigWithSpace, " {")
		file.P("\t", ctxArgName, ", tx, err := t.txr.Begin(", ctxArgName, ")")
		file.P("\tif err != nil {")

		if len(m.Results) == 1 {
			file.P("\t\treturn err")
		} else {
			file.P("\t\treturn ", strings.Join(zeroReturns, ", "), ", err")
		}
		file.P("\t}")
		file.P("\tdefer tx.Rollback()")
		file.P()

		if len(m.Results) == 1 {
			file.P("\tif err := t.next.", m.Name, "(", callArgs, "); err != nil {")
			file.P("\t\treturn err")
			file.P("\t}")
			file.P()
			file.P("\tif err := tx.Commit(); err != nil {")
			file.P("\t\treturn err")
			file.P("\t}")
			file.P()
			file.P("\treturn nil")
		} else if len(m.Results) == 2 {
			file.P("\tres, err := t.next.", m.Name, "(", callArgs, ")")
			file.P("\tif err != nil {")
			file.P("\t\treturn ", zeroReturns[0], ", err")
			file.P("\t}")
			file.P()
			file.P("\tif err := tx.Commit(); err != nil {")
			file.P("\t\treturn ", zeroReturns[0], ", err")
			file.P("\t}")
			file.P()
			file.P("\treturn res, nil")
		} else {
			var resNames []string
			for i := 0; i < len(m.Results)-1; i++ {
				resNames = append(resNames, fmt.Sprintf("res%d", i+1))
			}
			file.P("\t", strings.Join(resNames, ", "), ", err := t.next.", m.Name, "(", callArgs, ")")
			file.P("\tif err != nil {")
			file.P("\t\treturn ", strings.Join(zeroReturns, ", "), ", err")
			file.P("\t}")
			file.P()
			file.P("\tif err := tx.Commit(); err != nil {")
			file.P("\t\treturn ", strings.Join(zeroReturns, ", "), ", err")
			file.P("\t}")
			file.P()
			file.P("\treturn ", strings.Join(resNames, ", "), ", nil")
		}

		file.P("}")
		file.P()
	}

	return file, nil
}
